def join_text(raw):
    if isinstance(raw, str):
        return raw
    if isinstance(raw, list):
        parts = []
        for el in raw:
            if isinstance(el, str):
                parts.append(el)
            elif isinstance(el, dict):
                parts.append(str(el.get("text", "")))
            else:
                parts.append(str(el))
        return "".join(parts)
    return str(raw)


def main():
    exports = {}
    for ch in ("alko-trading", "wlsbot02", "grisha"):
        data = json.load(open(f"data/exports/{ch}/result.json"))
        items = data if isinstance(data, list) else data.get("messages", data)
        exports[ch] = {m.get("id"): m for m in items if isinstance(m, dict)}

    # дедуп: (channel,id) уже выписан — навигационные пометки склеиваем
    seen = {}
    order = []
    for ch, pid, title, nav in POSTS:
        key = (ch, pid)
        if key in seen:
            seen[key]["nav2"] = seen[key].get("nav2", []) + [nav]
        else:
            seen[key] = {"ch": ch, "pid": pid, "title": title, "nav": nav, "nav2": []}
            order.append(key)

    lines = []
    lines.append("# Точечные посты и фрагменты для гл. 9 «Лоу-латенси»")
    lines.append("")
    lines.append("Выписка дословных текстов для секций гл. 9. Источник: `data/exports/{канал}/result.json`")
    lines.append("(посты целиком, поля text склеены без изменений). Использовать только эти ID; цитаты —")
    lines.append("дословно, с ID. Навигационные пометки в скобках при заголовках — для воркеров, в главу не переносить.")
    lines.append("")
    cur_ch = None
    for key in order:
        rec = seen[key]
        if rec["ch"] != cur_ch:
            cur_ch = rec["ch"]
            lines.append(f"<!-- ===== канал {cur_ch} ===== -->")
            lines.append("")
        m = exports[rec["ch"]].get(rec["pid"])
        if m is None:
            raise SystemExit(f"MISSING: {rec['ch']}#{rec['pid']}")
        text = join_text(m.get("text", ""))
        navs = [rec["nav"]] + rec.get("nav2", [])
        nav_all = " ".join(navs)
        lines.append(f"## {rec['ch']}#{rec['pid']} — {rec['title']} (пост целиком)")
        lines.append(f"({nav_all})")
        lines.append("")
        lines.append(text)
        lines.append("")
    out = "\n".join(lines)
    path = "research/book/drafts/_posts-and-fragments-ch09.md"
    open(path, "w").write(out)
    print(f"wrote {path}: {len(order)} posts, {len(out.splitlines())} lines")


if __name__ == "__main__":
    main()
