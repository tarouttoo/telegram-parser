def load_exports():
    exports = {}
    for ch in ("alko-trading", "grisha", "wlsbot02"):
        d = json.load(open(f"data/exports/{ch}/result.json"))
        exports[ch] = {m["id"]: m for m in d["messages"]}
    return exports


def join_text(parts):
    if isinstance(parts, str):
        return parts
    out = []
    for p in parts:
        if isinstance(p, str):
            out.append(p)
        else:
            out.append(p.get("text", ""))
    return "".join(out)


def norm(s):
    return s.replace("ё", "е").replace("Ё", "Е")


def main():
    exports = load_exports()
    order, seen = [], {}
    for ch, pid, title, nav in POSTS:
        key = f"{ch}#{pid}"
        if key in seen:
            seen[key]["nav2"].append(nav)
            continue
        seen[key] = {"ch": ch, "pid": pid, "title": title, "nav": nav, "nav2": []}
        order.append(key)
    lines = [
        "# Дословные посты для гл. 15 «PnL, инвесторы и юрисдикция»",
        "",
        "Выписано программно из data/exports/*/result.json (без изменений).",
        "Каждый пост — целиком, дословно, с ID. Навигационные пометки в скобках при заголовках — для воркеров, в главу не переносить.",
        "",
    ]
    cur_ch = None
    texts = {}
    for key in order:
        rec = seen[key]
        if rec["ch"] != cur_ch:
            cur_ch = rec["ch"]
            lines.append(f"<!-- ===== канал {cur_ch} ===== -->")
            lines.append("")
        m = exports[rec["ch"]].get(rec["pid"])
        if m is None:
            raise SystemExit(f"MISSING: {rec['ch']}#{rec['pid']}")
        text = join_text(m.get("text", ""))
        texts[rec["pid"]] = text
        lines.append(f"## {rec['ch']}#{rec['pid']} — {rec['title']} (пост целиком)")
        lines.append(f"({rec['nav']})")
        lines.append("")
        lines.append(text)
        lines.append("")
    out = "\n".join(lines)
    path = "research/book/drafts/_posts-and-fragments-ch15.md"
    open(path, "w").write(out)
    print(f"wrote {path}: {len(order)} posts, {len(out.splitlines())} lines")

    bad = 0
    for pid, phrase in PHRASES:
        raw = texts.get(pid)
        if raw is None:
            print(f"Sverka: post #{pid} not in extract")
            bad += 1
            continue
        if phrase in raw or norm(phrase) in norm(raw):
            continue
        bad += 1
        print(f"MISMATCH #{pid}: «{phrase}» not found in raw")
    print(f"sverka doslovnosti: {len(PHRASES)} fraz, rashozhdeniy: {bad}")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
