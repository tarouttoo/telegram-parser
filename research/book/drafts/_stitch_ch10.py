import re

def load_sections(path):
    txt = open(path).read()
    if not txt.startswith("## "):
        txt = "## " + txt
    parts = re.split(r"\n## ", txt)
    return [p.strip() if i == 0 else "## " + p.strip() for i, p in enumerate(parts) if p.strip()]

def reflow(section):
    """Абзацы — в одну строку (кроме таблиц, списков, заголовков)."""
    out_lines = []
    para = []
    def flush():
        if para:
            joined = " ".join(l.strip() for l in para)
            out_lines.append(joined)
            para.clear()
    for line in section.split("\n"):
        s = line.strip()
        if (not s or s.startswith("|") or s.startswith("-") or s.startswith("#")
                or re.match(r"^\d+\.", s)):
            flush()
            out_lines.append(line.rstrip())
        else:
            para.append(line)
    flush()
    res = []
    for l in out_lines:
        if l == "" and res and res[-1] == "":
            continue
        res.append(l)
    return "\n".join(res)

